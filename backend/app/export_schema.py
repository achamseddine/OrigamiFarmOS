"""Renders `database/schema.sql` — the PostgreSQL DDL — from the ORM.

The schema the backend runs on is defined once, in the SQLAlchemy models
under `app/domain/`, and reaches a real database through the Alembic
migrations in `database/migrations/` (`alembic upgrade head`, which is
what `.github/workflows/migrate-seed-db.yml` runs). `database/schema.sql`
is that same schema rendered as plain PostgreSQL DDL, for reading and
review and for provisioning a database by hand without running the app.

It used to be hand-written and covered the first 52 tables; it then fell
behind every module added since. Rendering it from the metadata keeps it
honest by construction, and `tests/test_generated_artifacts.py` fails
whenever the committed file no longer matches the models, so it cannot
fall behind again without the suite saying so.

    cd backend && python -m app.export_schema          # rewrite the file
    cd backend && python -m app.export_schema --check  # exit 1 if it is stale

The migration parity test (`tests/test_migrations.py`) separately proves
the Alembic chain produces the same tables, columns, keys and indexes as
the models — so this file, the migrations and the ORM are one schema.
"""
from __future__ import annotations

import sys
from pathlib import Path

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from app.db.base import Base
from app.domain.registry import import_all

REPO_ROOT = Path(__file__).resolve().parents[2]
SCHEMA_PATH = REPO_ROOT / "database" / "schema.sql"

HEADER = """\
-- Origami FarmOS — PostgreSQL schema, rendered from the ORM metadata.
--
-- GENERATED FILE. Do not edit by hand: regenerate it with
--     cd backend && python -m app.export_schema
-- backend/tests/test_generated_artifacts.py fails when this file no longer
-- matches backend/app/domain/*.py.
--
-- How a real database gets this schema is Alembic:
--     cd backend && alembic -c alembic.ini upgrade head
-- (.github/workflows/migrate-seed-db.yml runs exactly that). The Alembic
-- chain is verified against these models table by table, column by column,
-- index by index in backend/tests/test_migrations.py, so this file, the
-- migrations and the ORM describe one schema.
--
-- Use this file to read or review the shape, or to provision a database
-- without running the application:
--     psql "$DATABASE_URL" -f database/schema.sql
--     cd backend && alembic -c alembic.ini stamp head   # so later migrations apply
-- Reference rows (units of measure, species, capability rules, feed and
-- medicine categories, ...) come from the migrations and seeders, not from
-- this file; `python -m app.seed` loads the demo farm,
-- `python -m app.seed_production` the real accounts.
--
-- Identifiers are 36-character strings (UUIDs are generated by the
-- application; demo data uses readable ids), timestamps are
-- TIMESTAMP WITH TIME ZONE holding UTC, and JSON columns are plain JSON —
-- the types the models declare and the migrations create.
"""


def render() -> str:
    """The full DDL as one deterministic string: tables in dependency
    order, each followed by its indexes."""
    import_all()
    dialect = postgresql.dialect()
    tables = list(Base.metadata.sorted_tables)
    index_count = sum(len(t.indexes) for t in tables)
    out = [HEADER, f"-- {len(tables)} tables, {index_count} secondary indexes.\n"]
    for table in tables:
        ddl = _tidy(str(CreateTable(table).compile(dialect=dialect)))
        out.append(f"\n{ddl};\n")
        for index in sorted(table.indexes, key=lambda i: i.name):
            out.append(_tidy(str(CreateIndex(index).compile(dialect=dialect))) + ";\n")
    return "".join(out)


def _tidy(ddl: str) -> str:
    """The compiler's output, without its trailing spaces and tabs."""
    return "\n".join(line.rstrip().replace("\t", "    ") for line in ddl.strip().splitlines())


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    text = render()
    if "--check" in args:
        current = SCHEMA_PATH.read_text(encoding="utf-8") if SCHEMA_PATH.exists() else ""
        if current != text:
            print(f"{SCHEMA_PATH.relative_to(REPO_ROOT)} is stale; run `python -m app.export_schema`.", file=sys.stderr)
            return 1
        print(f"{SCHEMA_PATH.relative_to(REPO_ROOT)} is current.")
        return 0
    SCHEMA_PATH.write_text(text, encoding="utf-8")
    print(f"Wrote {SCHEMA_PATH.relative_to(REPO_ROOT)} ({text.count('CREATE TABLE')} tables).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
